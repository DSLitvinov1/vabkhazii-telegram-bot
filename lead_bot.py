def detect_people(text):
    lower = text.lower()
    patterns = [
        r"\bнас\s+(\d{1,2})(?:\s*(?:человек(?:а|ов)?|чел)|(?:ро|еро))?\b",
        r"\b(\d{1,2})\s*человек(?:а|ов)?\b",
        r"\b(\d{1,2})\s*чел\b",
        r"\b(\d{1,2})\s*взросл",
        r"\bсемья\s+из\s+(\d{1,2})\b",
        r"\bкомпания\s+из\s+(\d{1,2})\b",
    ]

    for pattern in patterns:
        match = re.search(pattern, lower)
        if match:
            try:
                value = int(match.group(1))
                if 1 <= value <= 50:
                    return value
            except Exception:
                pass

    word_values = {
        "нас двое": 2,
        "нас трое": 3,
        "нас четверо": 4,
        "нас пятеро": 5,
        "нас шестеро": 6,
        "нас семеро": 7,
        "нас восьмеро": 8,
    }
    for phrase, value in word_values.items():
        if phrase in lower:
            return value

    return None


