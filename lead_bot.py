def detect_cis_origin(text, source_context=""):
    """
    Возвращает страну/рынок СНГ, явно упомянутый в сообщении или названии
    публичного источника. Источник используется только как запасной вариант.
    """
    if not CIS_ENABLED:
        return None

    text_lower = normalize(text).lower()
    source_lower = normalize(source_context).lower()

    for country, markers in CIS_ORIGINS.items():
        if any(marker in text_lower for marker in markers):
            return country

    for country, markers in CIS_ORIGINS.items():
        if any(marker in source_lower for marker in markers):
            return country

    return None


def detect_city(text):
    lower = text.lower()
    for city, variants in CITIES.items():
        if any(variant in lower for variant in variants):
            return city
    return None


def detect_route(text):
    lower = text.lower()
    for route, variants in ROUTES.items():
        if any(variant in lower for variant in variants):
            return route
    return None


def detect_people(text):
    lower = text.lower()
    patterns = [
        r"\bнас\s+(\d{1,2})\b",
        r"\b(\d{1,2})\s*человек\b",
        r"\b(\d{1,2})\s*чел\b",
        r"\b(\d{1,2})\s*взросл",
        r"\bсемья\s+из\s+(\d{1,2})\b",
        r"\bкомпания\s+из\s+(\d{1,2})\b",
    ]

    for pattern in patterns:
        match = re.search(pattern, lower)
        if match:
            try:
                value = int(match.group(1))
                if 1 <= value <= 50:
                    return value
            except Exception:
                pass

    word_values = {
        "нас двое": 2,
        "нас трое": 3,
        "нас четверо": 4,
        "нас пятеро": 5,
    }
    for phrase, value in word_values.items():
        if phrase in lower:
            return value

    return None


