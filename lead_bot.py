def looks_informational_only(text):
    lower = text.lower()
    info_hits = sum(1 for phrase in INFORMATIONAL_PHRASES if phrase in lower)
    if "границ" in lower and any(word in lower for word in ["открыт", "закрыт", "работает"]):
        info_hits += 1

    # Если одновременно есть сильная заявка на услугу, это всё ещё лид.
    if any(phrase in lower for phrase in DIRECT_SERVICE_PHRASES):
        return False

    # Вопрос про Рицу/Мзы/экскурсию может содержать слово «погода»,
    # но если человек явно хочет поездку — не режем.
    if any(phrase in lower for phrase in [
        "нужна экскурсия", "ищу экскурсию", "ищем экскурсию",
        "хочу на рицу", "хотим на рицу", "хотят на рицу", "хочу на мзы", "хотим на мзы", "хотят на мзы",
        "кто возит", "кто свозит",
    ]):
        return False

    return info_hits >= 1


def has_explicit_service_request(text):
    """Строгий признак прямой заявки именно на услугу."""
    lower = normalize(text).lower()

    if any(phrase in lower for phrase in DIRECT_SERVICE_PHRASES):
        return True

    # Естественные формулировки: «кто сегодня сможет отвезти...»,
    # «может кто забрать из аэропорта?» и т.п.
    if re.search(r"\bкто\b.{0,35}\b(?:сможет|может)?\s*(?:отвез|довез|забер|встрет|своз)", lower):
        return True
    if re.search(r"\b(?:может|сможет)\b.{0,20}\b(?:отвезти|довезти|забрать|встретить|свозить)", lower):
        return True

    has_service = any(marker in lower for marker in SERVICE_NOUNS)
    has_request = any(marker in lower for marker in SERVICE_REQUEST_WORDS)
    if has_service and has_request:
        return True

    # Явная формулировка с услугой и вопросом о цене.
    if has_service and "?" in text and any(word in lower for word in ["сколько", "цена", "стоимость"]):
        return True

    return False


def looks_like_route_discussion_only(text):
    """Обсуждение дороги/расстояния без запроса услуги не является лидом."""
    lower = normalize(text).lower()
    if has_explicit_service_request(text):
        return False

    markers = sum(1 for marker in ROUTE_DISCUSSION_MARKERS if marker in lower)
    if markers >= 1 and not any(phrase in lower for phrase in PLANNING_INTENT_PHRASES):
        return True

    # Фразы вида «150 км, это из Сухума до Сочи» — обычное обсуждение.
    if re.search(r"\b\d{2,4}\s*км\b", lower) and not any(
        word in lower for word in ["нуж", "ищ", "заказ", "кто может", "сколько стоит"]
    ):
        return True

    return False


def is_planning_request(text):
    lower = normalize(text).lower()

    if has_explicit_service_request(text):
        return False
    if looks_like_seller(text) or looks_like_broadcast_content(text):
        return False
    if looks_like_past_trip(text) or looks_like_advice_response(text):
        return False
    if looks_like_news_or_general_discussion(text):
        return False

    # Главная защита от мусора: месяц, «завтра», город или название Абхазии
    # сами по себе больше не делают сообщение planning-кандидатом.
    personal_future = has_personal_future_trip_intent(text)

    strong_planning_phrase = any(
        phrase in lower
        for phrase in [
            "куда поехать", "куда съездить", "куда сходить", "что посмотреть", "что посетить",
            "куда лучше поехать", "где лучше остановиться",
            "ищу попутчика", "ищем попутчиков", "ищу попутчиков", "ищем попутчика",
            "ищу компанию", "ищем компанию", "кто с нами", "кто поедет с нами",
            "хочу на рицу", "хотим на рицу", "хочу на мзы", "хотим на мзы",
            "хочу в новый афон", "хотим в новый афон",
        ]
    )

    # Вопросы «как добраться/доехать» полезны только когда это собственный запрос,
    # а не ответ/обсуждение дороги.
    route_question = any(
        phrase in lower
        for phrase in ["как добраться", "как доехать", "на чем добраться", "на чём добраться"]
    ) and ("?" in text or "подскаж" in lower or "пожалуйста" in lower)

    explicit_trip_phrase = any(phrase in lower for phrase in PLANNING_PHRASES)

    if personal_future:
        return True

    if strong_planning_phrase and (
        "?" in text or "подскаж" in lower or "посовет" in lower or "ищ" in lower or "хочу" in lower or "хотим" in lower
    ):
        return True

    if route_question and has_future_trip_signal(text):
        return True

    # PLANNING_PHRASES вроде «планируем поездку» уже содержат личное намерение,
    # но оставляем отдельную страховку на случай новых формулировок.
    if explicit_trip_phrase and has_future_trip_signal(text):
        return True

    return False


def has_direct_service_intent(text):
    # Теперь это строгое понятие: «как добраться», «кто едет», «куда поехать»
    # без запроса машины/трансфера/экскурсии не считаются прямым лидом.
    return has_explicit_service_request(text)


def strong_context_signals(text):
    """Контекст, повышающий прямую заявку до 🔥 горячей."""
    lower = normalize(text).lower()
    signals = []

    if detect_date_hint(text) or detect_urgency(text) or detect_time_hint(text):
        signals.append("есть дата/срочность")

    places = detect_all_places(text)
    if len(places) >= 2:
        signals.append("понятен маршрут")

    if detect_people(text):
        signals.append("указано количество людей")

    if detect_children(text):
        signals.append("есть дети")

    if detect_baggage(text):
        signals.append("есть багаж")

    if any(marker in lower for marker in ["аэропорт", "вокзал", "псоу", "границ"]):
        signals.append("конкретная точка поездки")

    if detect_route(text):
        signals.append("конкретная экскурсия/маршрут")

    return signals

def detect_lead_type(text):
    lower = normalize(text).lower()
    places = detect_all_places(text)

    transfer_score = sum(1 for phrase in TRANSFER_PHRASES if phrase in lower)
    companion_score = sum(1 for phrase in COMPANION_PHRASES if phrase in lower)
    excursion_score = sum(1 for phrase in EXCURSION_PHRASES if phrase in lower)

    movement = any(phrase in lower for phrase in MOVEMENT_PHRASES)
    companion_words = any(phrase in lower for phrase in [
        "ищу попут", "ищем попут", "кто едет", "едет кто", "кто-нибудь едет", "кто нибудь едет",
        "ищу компанию", "ищем компанию", "кто с нами",
    ])

    # Маршрут между двумя точками — прежде всего транспортная задача,
    # если нет явного экскурсионного контекста.
    if len(places) >= 2 and movement:
        transfer_score += 6

    if any(word in lower for word in [
        "трансфер", "машина", "такси", "водитель", "доехать", "добраться",
        "отвезти", "довезти", "забрать", "встретить", "аэропорт", "вокзал",
        "нужно в ", "надо в ",
    ]):
        transfer_score += 3

    if companion_words:
        companion_score += 4

    # Если «кто едет» + маршрут между городами, считаем попутчиками,
    # если нет явного запроса машины/трансфера.
    if companion_words and not any(word in lower for word in [
        "трансфер", "машина", "такси", "водитель", "отвез", "довез", "забер", "встрет",
    ]):
        companion_score += 4

    detected_route = detect_route(text)
    if detected_route:
        excursion_score += 2

    # Запросы по храмам и святыням трактуем как экскурсионный интерес,
    # даже если пользователь пишет «кто едет до Илора».
    shrine_markers = [
        "илор", "каманы", "дранда", "бедиа", "бедий",
        "монастыр", "храм", "святын", "святые места",
    ]
    shrine_intent = any(marker in lower for marker in shrine_markers)
    if shrine_intent:
        excursion_score += 10
        if any(phrase in lower for phrase in [
            "как попасть", "как доехать", "кто едет", "едет кто",
            "хочу", "хотим", "поехать", "съездить", "посетить",
        ]):
            excursion_score += 5
        # Чтобы «кто едет до Илора? Как попасть в храм?» не становилось
        # обычным добором попутчиков.
        companion_score = max(0, companion_score - 5)

    # Не позволяем одному названию Рицы/Нового Афона превращать транспортный
    # вопрос между городами в «экскурсию».
    if len(places) >= 2 and movement:
        excursion_score = max(0, excursion_score - 2)

    scores = {
        "transfer": transfer_score,
        "companions": companion_score,
        "excursion": excursion_score,
    }
    best_type = max(scores, key=scores.get)

    if scores[best_type] <= 0:
        return "unknown"
    return best_type


