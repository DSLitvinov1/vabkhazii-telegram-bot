async def search_public_messages(client, state, self_user_id):
    cutoff = datetime.now(timezone.utc) - timedelta(hours=MAX_AGE_HOURS)
    stats = new_filter_stats()

    # Четыре независимых потока поиска:
    # 1) глобальный Telegram-поиск;
    # 2) наш белый список;
    # 3) автоматическое обнаружение новых публичных туристических групп;
    # 4) тематические группы, в которые пользователь уже вступил сам.
    global_results, chat_results, discovered_results, joined_results = await asyncio.gather(
        global_search_worker(client, state, cutoff, self_user_id, stats),
        chat_scan_worker(client, state, cutoff, self_user_id, stats),
        discovered_chat_scan_worker(client, state, cutoff, self_user_id, stats),
        joined_chat_scan_worker(client, state, cutoff, self_user_id, stats),
    )

    candidates = {}
    for source in (global_results, chat_results, discovered_results, joined_results):
        for item in source.values():
            merge_candidate(candidates, item)

    result = list(candidates.values())
    direct = [item for item in result if item["classification"].get("bucket") == "direct"]
    planning = [item for item in result if item["classification"].get("bucket") == "planning"]

    direct.sort(
        key=lambda item: (item["classification"]["score"], item["date"]),
        reverse=True,
    )
    planning.sort(key=lambda item: item["date"], reverse=True)

    return direct[:MAX_LEADS_PER_RUN], planning[:12], stats


def make_planning_digest(planning):
    if not planning:
        return None

    lines = [
        "🟠 <b>ПЛАНИРУЮТ ПОЕЗДКУ — СВОДКА</b>",
        "",
        "Это не прямые заявки на трансфер/экскурсию, но люди уже планируют поездку.",
        "Можно использовать для аккуратного полезного ответа без навязчивой продажи.",
        "",
    ]

    for idx, item in enumerate(planning[:10], start=1):
        text = item["text"]
        short = text[:260] + ("…" if len(text) > 260 else "")

        if item.get("source_kind") == "external_web":
            source_name = item.get("source_name", "Внешняя площадка")
            link = item.get("url")
            lines.append(f"<b>{idx}. Внешняя площадка</b> · {html.escape(source_name)}")
            lines.append(html.escape(short))
            if link:
                lines.append(f'<a href="{html.escape(link)}">Открыть страницу</a>')
            lines.append("")
            continue

        chat = item["chat"]
        sender = item["sender"]
        link = build_message_link(chat, item["message_id"])
        sender_name = " ".join(
            part for part in [getattr(sender, "first_name", None), getattr(sender, "last_name", None)] if part
        ).strip() or "Пользователь"
        lines.append(f"<b>{idx}. {html.escape(sender_name)}</b> · {html.escape(source_title(chat))}")
        lines.append(html.escape(short))
        if link:
            lines.append(f'<a href="{html.escape(link)}">Открыть сообщение</a>')
        lines.append("")

    result = "\n".join(lines)
    return result[:3900]


