async def message_to_candidate(
    client,
    message,
    cutoff,
    state,
    source_kind,
    source_name,
    self_user_id,
    stats,
    allow_reply_lookup=True,
):
    if not message:
        return None

    bump_stat(stats, "messages_seen")
    bump_source(stats, source_name, "seen")

    if getattr(message, "out", False) or getattr(message, "post", False):
        bump_stat(stats, "own_or_channel_post")
        return None

    if getattr(message, "fwd_from", None) or getattr(message, "via_bot_id", None):
        bump_stat(stats, "forwarded_or_via_bot")
        return None

    text = normalize(getattr(message, "message", ""))
    if not text or not message.date:
        bump_stat(stats, "empty_or_no_date")
        return None

    date = message.date
    if date.tzinfo is None:
        date = date.replace(tzinfo=timezone.utc)
    if date < cutoff:
        bump_stat(stats, "too_old")
        return None

    chat = await message.get_chat()
    if source_kind == "joined":
        if not is_joined_tourist_chat(chat):
            bump_stat(stats, "blocked_or_nonpublic_chat")
            return None
    else:
        if not is_allowed_chat(chat):
            bump_stat(stats, "blocked_or_nonpublic_chat")
            return None

    try:
        sender = await message.get_sender()
    except Exception:
        sender = None

    if not is_allowed_sender(sender, self_user_id):
        bump_stat(stats, "invalid_sender")
        return None

    if looks_like_commercial_sender(sender, text):
        bump_stat(stats, "commercial_sender")
        return None

    unique_id = f"{getattr(chat, 'id', '')}:{message.id}"
    if unique_id in state.get("seen", []):
        bump_stat(stats, "duplicate")
        return None

    context_hint = f"{source_name} {source_title(chat)}"

    # Не подменяем ответ другого человека исходным вопросом: оригинальный автор
    # будет найден при обычном сканировании. Так Julia/советчики не создают дубль.
    if looks_like_past_trip(text):
        bump_stat(stats, "past_trip_filtered")
        return None
    if looks_like_advice_response(text):
        bump_stat(stats, "reply_advice_filtered")
        bump_stat(stats, "advice_response")
        return None

    classification, reject_reason = classify_lead_detailed(text, source_context=context_hint)

    # Слабое соседнее сообщение сохраняем только как контекст будущей цепочки
    # того же автора: например «нас 5, нужен минивэн» или «будем завтра».
    if not classification:
        if reject_reason in {
            "no_direct_service_intent", "informational_only",
            "no_abkhazia_context", "unknown_service_type",
        } and is_chain_context_message(text, context_hint):
            return {
                "id": unique_id,
                "message_id": message.id,
                "text": text,
                "date": date,
                "chat": chat,
                "chat_id": getattr(chat, "id", None),
                "sender": sender,
                "sender_id": getattr(sender, "id", None),
                "sender_username": getattr(sender, "username", None),
                "classification": None,
                "reject_reason": reject_reason,
                "source_kind": source_kind,
                "source_name": source_name,
                "context_hint": context_hint,
            }

        if reject_reason:
            bump_stat(stats, reject_reason)
        return None

    return {
        "id": unique_id,
        "message_id": message.id,
        "text": text,
        "date": date,
        "chat": chat,
        "chat_id": getattr(chat, "id", None),
        "sender": sender,
        "sender_id": getattr(sender, "id", None),
        "sender_username": getattr(sender, "username", None),
        "classification": classification,
        "source_kind": source_kind,
        "source_name": source_name,
        "context_hint": context_hint,
    }


def merge_candidate(candidates, item):
    if not item:
        return

    current = candidates.get(item["id"])
    if current is None:
        candidates[item["id"]] = item
        return

    # Один и тот же Telegram message может встретиться через GLOBAL и через чат.
    # Предпочитаем запись с распознанной классификацией и более конкретным источником.
    current_score = (current.get("classification") or {}).get("score", -1)
    item_score = (item.get("classification") or {}).get("score", -1)
    source_rank = {"joined": 4, "whitelist": 3, "discovered": 2, "global": 1}
    if item_score > current_score or (
        item_score == current_score
        and source_rank.get(item.get("source_kind"), 0) > source_rank.get(current.get("source_kind"), 0)
    ):
        candidates[item["id"]] = item


def candidate_chain_key(item):
    chat_id = item.get("chat_id") or getattr(item.get("chat"), "id", None) or "unknown-chat"
    sender_id = item.get("sender_id") or getattr(item.get("sender"), "id", None)
    if sender_id is not None:
        return (str(chat_id), f"id:{sender_id}")

    username = (item.get("sender_username") or getattr(item.get("sender"), "username", None) or "").lower()
    if username:
        return (str(chat_id), f"user:{username}")

    # Без идентификатора автора не склеиваем разные сообщения.
    return (str(chat_id), f"message:{item.get('id')}")


def split_author_chains(items):
    groups = {}
    for item in items:
        groups.setdefault(candidate_chain_key(item), []).append(item)

    chains = []
    window = timedelta(hours=CHAIN_WINDOW_HOURS)
    for grouped in groups.values():
        grouped.sort(key=lambda x: x["date"])
        current = []
        previous_date = None
        for item in grouped:
            if previous_date is None or item["date"] - previous_date <= window:
                current.append(item)
            else:
                if current:
                    chains.append(current)
                current = [item]
            previous_date = item["date"]
        if current:
            chains.append(current)
    return chains


def aggregate_telegram_candidates(items, stats):
    aggregated = []

    for chain in split_author_chains(items):
        chain.sort(key=lambda x: x["date"])
        # Убираем повторы текста, если один message пришёл из нескольких поисковых путей.
        unique_texts = []
        seen_texts = set()
        for item in chain:
            value = normalize(item.get("text", ""))
            if value and value not in seen_texts:
                unique_texts.append(value)
                seen_texts.add(value)
        combined_text = "\n".join(unique_texts)
        if not combined_text:
            continue

        anchor = max(chain, key=lambda x: x["date"])
        source_context = " ".join(
            dict.fromkeys(
                normalize(item.get("context_hint") or "")
                for item in chain
                if item.get("context_hint")
            )
        )

        classification, reject_reason = classify_lead_detailed(combined_text, source_context=source_context)
        if not classification:
            if reject_reason:
                bump_stat(stats, reject_reason)
            continue

        if len(chain) > 1:
            bump_stat(stats, "merged_chains")
            bump_stat(stats, "merged_messages", len(chain))

        if not has_abkhazia_context(combined_text) and has_abkhazia_source_context(source_context):
            bump_stat(stats, "source_context_used")

        source_name = anchor.get("source_name") or "Telegram"
        if classification.get("bucket") == "planning":
            bump_stat(stats, "planning_candidate")
            bump_source(stats, source_name, "planning")
        else:
            bump_stat(stats, "accepted")
            if classification.get("temperature") == "hot":
                bump_stat(stats, "hot_leads")
            elif classification.get("temperature") == "warm":
                bump_stat(stats, "warm_leads")
            bump_source(stats, source_name, "accepted")

        all_seen_ids = [item["id"] for item in chain]
        all_message_ids = [item["message_id"] for item in chain]
        aggregated.append({
            "id": anchor["id"],
            "seen_ids": all_seen_ids,
            "message_ids": all_message_ids,
            "message_id": anchor["message_id"],
            "text": combined_text,
            "date": anchor["date"],
            "chat": anchor["chat"],
            "sender": anchor["sender"],
            "classification": classification,
            "source_kind": anchor.get("source_kind"),
            "source_name": source_name,
            "chain_count": len(chain),
        })

    return aggregated


async def global_search_worker(client, state, cutoff, self_user_id, stats):
    candidates = {}

    if not state_interval_due(
        state.get("global_last_scan"),
        GLOBAL_SEARCH_INTERVAL_MINUTES,
    ):
        print(
            f"[GLOBAL] skipped: full Telegram search runs every "
            f"{GLOBAL_SEARCH_INTERVAL_MINUTES} minutes"
        )
        return candidates

    try:
        for query in SEARCH_QUERIES:
            print(f"[GLOBAL] {query}")
            try:
                async for message in client.iter_messages(None, search=query, limit=SEARCH_LIMIT):
                    item = await message_to_candidate(
                        client,
                        message,
                        cutoff,
                        state,
                        "global",
                        "GLOBAL",
                        self_user_id,
                        stats,
                    )
                    merge_candidate(candidates, item)

            except FloodWaitError as exc:
                print(f"[FLOOD WAIT] {exc.seconds}s on query: {query}")
                if exc.seconds <= 60:
                    await asyncio.sleep(exc.seconds + 1)
                else:
                    break
            except Exception as exc:
                print(f"[GLOBAL WARNING] {query}: {exc}")

            await asyncio.sleep(QUERY_DELAY_SECONDS)
    finally:
        # Даже если отдельный запрос дал ошибку, не долбим Telegram полным
        # поиском каждые 5 минут. Обычные целевые/вступленные чаты всё равно
        # продолжают проверяться на каждом запуске.
        mark_state_time(state, "global_last_scan")

    return candidates


async def chat_scan_worker(client, state, cutoff, self_user_id, stats):
    candidates = {}

    for chat_ref in TARGET_CHATS:
        source_name = f"@{chat_ref}"
        print(f"[CHAT] {source_name}")
        try:
            entity = await client.get_entity(chat_ref)
            cursor = get_chat_cursor(state, entity, "whitelist")
            newest_id = cursor
            kwargs = {"limit": CHAT_SCAN_LIMIT}
            if cursor > 0:
                kwargs["min_id"] = cursor

            async for message in client.iter_messages(entity, **kwargs):
                newest_id = max(newest_id, int(getattr(message, "id", 0) or 0))

                # На первом проходе сохраняем прежнюю глубину 72 часа. После
                # появления курсора читаются только сообщения новее cursor.
                if cursor == 0 and message.date:
                    date = message.date
                    if date.tzinfo is None:
                        date = date.replace(tzinfo=timezone.utc)
                    if date < cutoff:
                        break

                item = await message_to_candidate(
                    client,
                    message,
                    cutoff,
                    state,
                    "whitelist",
                    source_name,
                    self_user_id,
                    stats,
                )
                merge_candidate(candidates, item)

            if newest_id > cursor:
                update_chat_cursor(state, entity, "whitelist", newest_id)

        except FloodWaitError as exc:
            print(f"[CHAT FLOOD WAIT] {source_name}: {exc.seconds}s")
            if exc.seconds <= 60:
                await asyncio.sleep(exc.seconds + 1)
        except Exception as exc:
            print(f"[CHAT WARNING] {source_name}: {exc}")

    return candidates


async def get_discovered_chats_for_scan(client, state):
    if not state_interval_due(
        state.get("discovered_last_scan"),
        DISCOVERED_SCAN_INTERVAL_MINUTES,
    ):
        print(
            f"[DISCOVERED CHAT] skipped: scan runs every "
            f"{DISCOVERED_SCAN_INTERVAL_MINUTES} minutes"
        )
        return []

    mark_state_time(state, "discovered_last_scan")

    refresh_due = state_interval_due(
        state.get("discovery_refresh_last_scan"),
        DISCOVERY_REFRESH_INTERVAL_MINUTES,
    )
    cached = [
        str(x).strip().lstrip("@")
        for x in state.get("discovered_chat_usernames", [])
        if str(x).strip()
    ]

    if refresh_due or not cached:
        chats = await discover_public_tourist_chats(client)
        usernames = []
        for chat in chats:
            username = getattr(chat, "username", None)
            if username:
                usernames.append(str(username).lstrip("@"))
        state["discovered_chat_usernames"] = list(dict.fromkeys(usernames))[:MAX_DISCOVERED_CHATS]
        mark_state_time(state, "discovery_refresh_last_scan")
        return chats

    chats = []
    for username in cached[:MAX_DISCOVERED_CHATS]:
        try:
            entity = await client.get_entity(username)
            if is_discovery_candidate_chat(entity):
                chats.append(entity)
        except Exception as exc:
            print(f"[DISCOVERED CACHE WARNING] @{username}: {exc}")
    return chats


async def discovered_chat_scan_worker(client, state, cutoff, self_user_id, stats):
    candidates = {}
    chats = await get_discovered_chats_for_scan(client, state)

    for entity in chats:
        username = getattr(entity, "username", None) or "unknown"
        source_name = f"@{username}"
        print(f"[DISCOVERED CHAT] {source_name}")

        try:
            cursor = get_chat_cursor(state, entity, "discovered")
            newest_id = cursor
            kwargs = {"limit": DISCOVERY_CHAT_SCAN_LIMIT}
            if cursor > 0:
                kwargs["min_id"] = cursor

            async for message in client.iter_messages(entity, **kwargs):
                newest_id = max(newest_id, int(getattr(message, "id", 0) or 0))

                if cursor == 0 and message.date:
                    date = message.date
                    if date.tzinfo is None:
                        date = date.replace(tzinfo=timezone.utc)
                    if date < cutoff:
                        break

                item = await message_to_candidate(
                    client,
                    message,
                    cutoff,
                    state,
                    "discovered",
                    source_name,
                    self_user_id,
                    stats,
                )
                merge_candidate(candidates, item)

            if newest_id > cursor:
                update_chat_cursor(state, entity, "discovered", newest_id)

        except FloodWaitError as exc:
            print(f"[DISCOVERED CHAT FLOOD WAIT] {source_name}: {exc.seconds}s")
            if exc.seconds <= 60:
                await asyncio.sleep(exc.seconds + 1)
        except Exception as exc:
            print(f"[DISCOVERED CHAT WARNING] {source_name}: {exc}")

    return candidates


