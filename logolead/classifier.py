def norm(value):
    return ' '.join((value or '').split()).strip()


def extract(text):
    t = norm(text).lower()
    age = None
    match = re.search(r'(?<!\d)(1[0-7]|[1-9])(?:[.,](\d))?\s*(?:лет|года|год|г\.?)(?!\w)', t)
    months_match = re.search(r'(?<!\d)(1[0-7]|[1-9])\s*(?:года|год|лет)\s*(1[01]|[1-9])\s*(?:месяц(?:а|ев)?|мес\.?)', t)
    if months_match:
        years=int(months_match.group(1)); months=int(months_match.group(2))
        age=round(years+months/12,2)
        match=None
    if age is None and not match:
        match = re.search(r'(?:реб[её]нку|сыну|дочк[еий]|дочери)\s*(1[0-7]|[1-9])(?:[.,](\d))?(?=\s|[,.;!?]|$)', t)
    if age is None and match:
        age = float(match.group(1) + '.' + match.group(2)) if match.group(2) else int(match.group(1))
    if age is None:
        hyphen = re.search(r'(?<!\d)(1[0-7]|[1-9])[-\s]?летн\w*', t)
        if hyphen:
            age=int(hyphen.group(1))
    if age is None:
        for word,value in AGE_WORDS.items():
            if re.search(rf'\b{word}\s+(?:год|года|лет)\b',t) or re.search(rf'(?:реб[её]нку|сыну|дочк[еий]|дочери)\s+{word}\b',t):
                age=value
                break
    city = next((label for pattern,label in CITY_PATTERNS if re.search(pattern,t)), None)
    online_terms=('онлайн','дистанционно','удаленно','удалённо','по видеосвязи','по скайпу','skype','zoom','зум')
    offline_terms=('очно','офлайн','в кабинете','лично','с выездом','на дому')
    mode = 'онлайн' if any(x in t for x in online_terms) else ('очно' if any(x in t for x in offline_terms) else None)
    return {'age': age, 'city': city, 'mode': mode}


def score(text):
    t = norm(text).lower()
    why = []
    specialist_mentioned=any(x in t for x in ['логопед','дефектолог','нейрологопед'])
    if re.search(r'(^|[\s,.!?:;])я\s+(логопед|дефектолог)\b', t) or any(x in t for x in SELLER_STRONG):
        return 0, ['предложение специалиста']
    if specialist_mentioned and t.count('#')>=3:
        return 0, ['рекламный пост/хэштеги']
    if specialist_mentioned and re.search(r'(?:запись|записаться|whatsapp|ватсап|телефон|тел\.)[^\n]{0,60}\+?\d[\d\s()\-]{7,}',t):
        return 0, ['рекламный контакт']
    if ('логопед' in t or 'дефектолог' in t) and any(x in t for x in SELLER_CONTEXT):
        return 0, ['реклама специалиста']
    if any(x in t for x in JOBS) or (('логопед' in t or 'дефектолог' in t) and any(x in t for x in JOB_CONTEXT)):
        return 0, ['вакансия/поиск сотрудника']
    if any(x in t for x in NOISE):
        return 0, ['нерелевантное обучение/контент']

    direct_hit=any(x in t for x in HOT)
    if direct_hit and any(x in t for x in NON_CLIENT_CONTEXT):
        return 0, ['не клиентский запрос к специалисту']
    if not direct_hit and any(x in t for x in CONTENT_NOISE):
        return 0, ['информационный/экспертный контент']
    ambiguous_hit=any(x in t for x in AMBIGUOUS)
    need_hit=any(x in t for x in NEED)
    urgent_hit=any(x in t for x in URGENT)
    help_hit=any(x in t for x in HELP)
    question_hit='?' in t
    specialist_hit=specialist_mentioned
    meta=extract(t)
    personal_hit=meta['age'] is not None or any(x in t for x in [
        'моему ребенку','моему ребёнку','мой ребенок','мой ребёнок','наш ребенок','наш ребёнок',
        'ребенку','ребёнку','сыну','сын ','дочке','дочери','дочь ',
    ])

    points=0
    if direct_hit:
        points+=55; why.append('прямой поиск специалиста')
    elif ambiguous_hit:
        points+=35; why.append('похоже на краткий запрос')
    if need_hit:
        points+=25; why.append('описана речевая проблема')
    if urgent_hit:
        points+=10; why.append('срочность')
    if help_hit and need_hit:
        points+=25; why.append('просит помощи со специалистом')
    elif question_hit and need_hit:
        points+=25; why.append('вопрос о речевой проблеме')
    if ambiguous_hit and not direct_hit and personal_hit:
        points+=10; why.append('есть контекст ребенка')
    if meta['mode'] or meta['city']:
        points+=5; why.append('формат/география')
    if meta['age'] is not None:
        points+=5; why.append('возраст ребенка')
    if points==0 and specialist_hit and (question_hit or 'подскажите' in t):
        points=25; why.append('вопрос о специалисте')
    if ambiguous_hit and not direct_hit and not help_hit and not question_hit and not personal_hit:
        points=min(points,45)
    return min(100,points),why
