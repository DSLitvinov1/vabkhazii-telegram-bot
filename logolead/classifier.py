def norm(value):
    return ' '.join((value or '').split()).strip()


def extract(text):
    t = norm(text).lower()
    age = None
    match = re.search(r'(?<!\d)(1[0-7]|[1-9])(?:[.,](\d))?\s*(?:лет|года|год)', t)
    if match:
        age = float(match.group(1) + '.' + match.group(2)) if match.group(2) else int(match.group(1))
    city = next((city.title() for city in CITIES if city in t), None)
    mode = 'онлайн' if 'онлайн' in t else ('очно' if 'очно' in t else None)
    return {'age': age, 'city': city, 'mode': mode}


def score(text):
    t = norm(text).lower()
    why = []
    if re.search(r'(^|[\s,.!?:;])я\s+(логопед|дефектолог)\b', t) or any(x in t for x in SELLER_STRONG):
        return 0, ['предложение специалиста']
    if ('логопед' in t or 'дефектолог' in t) and any(x in t for x in SELLER_CONTEXT):
        return 0, ['реклама специалиста']
    if any(x in t for x in JOBS) or (('логопед' in t or 'дефектолог' in t) and any(x in t for x in JOB_CONTEXT)):
        return 0, ['вакансия/поиск сотрудника']
    if any(x in t for x in NOISE):
        return 0, ['нерелевантное обучение/контент']

    points = 0
    if any(x in t for x in HOT):
        points += 55; why.append('прямой поиск специалиста')
    if any(x in t for x in NEED):
        points += 25; why.append('описана речевая проблема')
    if any(x in t for x in URGENT):
        points += 10; why.append('срочность')
    if any(x in t for x in HELP) and any(x in t for x in NEED):
        points += 25; why.append('просит помощи со специалистом')
    meta = extract(t)
    if meta['mode'] or meta['city']:
        points += 5; why.append('формат/география')
    if meta['age'] is not None:
        points += 5; why.append('возраст ребенка')
    if points == 0 and ('логопед' in t or 'дефектолог' in t) and ('?' in t or 'подскажите' in t):
        points = 25; why.append('вопрос о специалисте')
    return min(100, points), why
