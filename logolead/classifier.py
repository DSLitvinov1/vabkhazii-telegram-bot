import re
SELLER=['я логопед','я дефектолог','логопед набирает','набираю учеников','набираю детей','услуги логопеда','консультация логопеда','веду прием','веду приём','запись на занятия','записывайтесь','логопедический центр','приглашаю на занятия','места на занятия','провожу занятия','стоимость занятия','прайс','скидка на занятия','мой кабинет']
JOBS=['вакансия логопед','требуется логопед','ищем логопеда в команду','ищем логопеда в детский','ищем дефектолога в команду','работа логопедом','зарплата логопед','резюме логопед']
HOT=['ищу логопеда','ищем логопеда','нужен логопед','нужна логопед','посоветуйте логопеда','посоветуйте хорошего логопеда','порекомендуйте логопеда','кто знает хорошего логопеда','кто знает логопеда','подскажите логопеда','нужен специалист по речи','ищу специалиста для ребенка','ищу специалиста для ребёнка','ищу дефектолога','ищем дефектолога','нужен дефектолог','посоветуйте дефектолога']
NEED=['не говорит','плохо говорит','не выговаривает','запуск речи','зрр','зпрр','дисграф','дислекс','постановка звуков','произнош','картавит','шепеляв','заика','задержка речи','онр','ффнр','дизартр']
URGENT=['срочно','сегодня','как можно скорее','нужно сейчас','очень нужен','желательно сегодня']
NOISE=['курсовая','дипломная работа','реферат','обучение логопедов','курс для логопедов','вебинар для логопедов','сертификат логопеда','повышение квалификации','методичка для логопеда']
CITIES=['москва','санкт-петербург','спб','краснодар','сочи','ростов','казань','екатеринбург','новосибирск','красноярск','минск','алматы','астана','тбилиси']
def norm(s): return ' '.join((s or '').split()).strip()
def extract(text):
    t=norm(text).lower(); age=None
    m=re.search(r'([2-9]|1[0-7])[ ]*(?:лет|года|год)',t)
    if m: age=int(m.group(1))
    city=next((c.title() for c in CITIES if c in t),None)
    mode='онлайн' if 'онлайн' in t else ('очно' if 'очно' in t else None)
    return {'age':age,'city':city,'mode':mode}
def score(text):
    t=norm(text).lower(); why=[]
    if any(x in t for x in SELLER): return 0,['предложение специалиста']
    if any(x in t for x in JOBS): return 0,['вакансия/поиск сотрудника']
    if any(x in t for x in NOISE): return 0,['нерелевантное обучение/контент']
    n=0
    if any(x in t for x in HOT): n+=55; why.append('прямой поиск специалиста')
    if any(x in t for x in NEED): n+=25; why.append('описана речевая проблема')
    if any(x in t for x in URGENT): n+=10; why.append('срочность')
    meta=extract(t)
    if meta['mode'] or meta['city']: n+=5; why.append('формат/география')
    if meta['age'] is not None: n+=5; why.append('возраст ребенка')
    if n==0 and ('логопед' in t or 'дефектолог' in t) and ('?' in t or 'подскажите' in t): n=25; why.append('вопрос о специалисте')
    return min(100,n),why
